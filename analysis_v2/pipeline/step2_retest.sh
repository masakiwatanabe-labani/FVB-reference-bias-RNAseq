#!/bin/bash
# Speed-up Step 2 re-test (approved 2026-10-17, condition 2): same test animal, BOTH arms, shared-memory mapping
# (LoadAndKeep, no mapping-time GTF, BAM Unsorted + samtools sort, 2 concurrent x 4 threads) against the B6 index and the
# REBUILT FVB index (ref/star_fvb_b6gtf). Adoption only if, for every test run, (a) md5 of BAM records sorted by
# (name, flag, chr, pos, CIGAR, vW), (b) md5 of whole records (all tags), (c) flagstat and (d) all five production count
# matrices (naive/wasp/fvb unique, naive/fvb -M --fraction; data rows only) are identical to the production run.
# Mapping phase holds the STAR lock; the comparison phase runs after the lock is released.
set -uo pipefail
PROJ=/usr/local/jupyter/FVB_bias; SID=${1:-hypothalamus_B6_CWHyp4}
eval "$(python3 -I $PROJ/analysis_v2/pipeline/manifest_row.py "$SID")"
D=$PROJ/analysis_v2/data/$M_tissue/$SID
W=${2:-/tmp/claude-0/-usr-local-jupyter-FVB-bias/e900eed5-e9ea-4c20-a6d8-90c422bc83a4/scratchpad/step2}   # holds r1/r2.fq.gz, prod.naive.bam, prod.fvb.bam from the first test
TAG=${TAG:-}; ARMS=${ARMS:-"naive fvb"}   # TAG/ARMS/FVB_INDEX: variant re-tests (e.g. fvb arm only against another rebuilt index)
R=$W/retest$TAG; mkdir -p $R
OUT=$PROJ/revision_v2/speedup/06${TAG}_shm_retest_b6gtf_index.md
STAR=/usr/local/bin/STAR; SAMTOOLS=/usr/local/bin/samtools; FC=/usr/local/bin/featureCounts
GTF=$PROJ/ref/b6_gtf/GRCm39.110.gtf; VCF=$PROJ/ref/fvb_vcf/FVB_NJ.snps.GRCm39.vcf
STAR_B6=$PROJ/ref/star_b6; STAR_FVB=${FVB_INDEX:-$PROJ/ref/star_fvb_b6gtf}; LOCK=$PROJ/analysis_v2/locks/star.lock
log(){ echo "[$(date '+%F %T')] retest $*"; }
PE=0; [ "$M_library_layout" = "PAIRED" ] && PE=1; PF=""; [ $PE -eq 1 ] && PF="-p"
if [ $PE -eq 1 ]; then READS="$W/r1.fq.gz $W/r2.fq.gz"; else READS="$W/r1.fq.gz"; fi
for f in $READS $W/prod.naive.bam $W/prod.fvb.bam $D/counts/$SID.naive.unique.txt $D/counts/$SID.wasp.unique.txt $D/counts/$SID.fvb.unique.txt $D/counts/$SID.naive.multi.txt $D/counts/$SID.fvb.multi.txt; do [ -s $f ] || { log "missing input $f"; exit 2; }; done
RG="ID:$SID SM:$SID PL:ILLUMINA"
until [ -e $STAR_FVB/done.build ]; do sleep 60; done; log "rebuilt FVB index present"

run_arm(){ # $1 arm  $2 genomeDir  $3 extra args
  local arm=$1 g=$2 extra=$3 t0 t1 t2 t3
  t0=$(date +%s)
  $STAR --genomeLoad LoadAndExit --genomeDir $g --outFileNamePrefix $R/$arm.load. > $R/$arm.load.log 2>&1 || { log "$arm: LoadAndExit FAILED"; return 1; }
  t1=$(date +%s); log "$arm: genome loaded in $((t1-t0)) s (RAM avail $(free -g | awk 'NR==2{print $7}') G); two concurrent mappings, 4 threads each"
  for k in 1 2; do
    $STAR --runThreadN 4 --genomeLoad LoadAndKeep --genomeDir $g --readFilesIn $READS --readFilesCommand zcat \
      --outSAMtype BAM Unsorted --outSAMstrandField intronMotif --outFilterIntronMotifs RemoveNoncanonical $extra \
      --outSAMattrRGline $RG --outFileNamePrefix $R/$arm.$k. > $R/$arm.$k.log 2>&1 &
  done
  wait; t2=$(date +%s); log "$arm: both mappings done in $((t2-t1)) s"
  for k in 1 2; do $SAMTOOLS sort -@ 4 -m 1G -o $R/$arm.$k.bam $R/$arm.$k.Aligned.out.bam 2> $R/$arm.$k.sort.log || log "$arm.$k: sort failed"; done
  t3=$(date +%s); log "$arm: sorted in $((t3-t2)) s"
  $STAR --genomeLoad Remove --genomeDir $g --outFileNamePrefix $R/$arm.remove. > $R/$arm.remove.log 2>&1
  echo "$arm load=$((t1-t0)) map2x=$((t2-t1)) sort2x=$((t3-t2))" >> $R/timings.txt
  rm -f $R/$arm.[12].Aligned.out.bam
}
log "waiting for STAR lock"
( /usr/bin/flock 9
  log "STAR lock acquired; mapping phase"
  for arm in $ARMS; do
    [ $arm = naive ] && run_arm naive $STAR_B6 "--waspOutputMode SAMtag --varVCFfile $VCF --outSAMattributes NH HI AS NM MD vW"
    [ $arm = fvb ] && run_arm fvb $STAR_FVB ""
  done
  for g in $STAR_B6 $STAR_FVB; do $STAR --genomeLoad Remove --genomeDir $g --outFileNamePrefix $R/cleanup.$(basename $g). > /dev/null 2>&1; done
  log "mapping phase complete; lock released"
) 9>$LOCK

# ---- comparison phase (no STAR, lock free) ----
sig(){ $SAMTOOLS view $1 | awk 'BEGIN{OFS="\t"}{t="-"; for(i=12;i<=NF;i++) if($i ~ /^vW:i:/) t=$i; print $1,$2,$3,$4,$6,t}' | LC_ALL=C sort -S 2G | md5sum | cut -d' ' -f1; }
sigfull(){ $SAMTOOLS view $1 | LC_ALL=C sort -S 2G | md5sum | cut -d' ' -f1; }
fcmd5(){ grep -v '^#' $1 | tail -n +2 | cut -f1,7 | md5sum | cut -d' ' -f1; }   # data rows only (header carries the BAM path)
NBAD=0; chk(){ [ "$1" = "$2" ] && echo yes || echo "**NO**"; }   # BUG FIXED 2026-10-17 18:10: a counter incremented inside $(...) is lost; the verdict now counts "**NO**" cells in the report
log "comparison phase"
{
echo "# Speed-up Step 2 re-test — shared-memory mapping with the FVB index rebuilt on the B6 GTF"; echo
echo "Animal: $SID ($M_tissue, $M_strain, $M_library_layout). Generated by analysis_v2/pipeline/step2_retest.sh on $(date '+%F %T')."
echo "Production reference: the run recorded in \`$D/logs/run_sample.log\` (old FVB index + mapping-time B6 GTF insertion; STAR 8 threads, built-in sort). Test: \`--genomeLoad LoadAndKeep\`, no \`--sjdbGTFfile\`, \`BAM Unsorted\` + \`samtools sort -@4 -m 1G\`, two mappings per arm concurrently with 4 threads each; naive arm on \`ref/star_b6\`, FVB arm on \`ref/star_fvb_b6gtf\` (built $(date -r $STAR_FVB/done.build '+%F %T'), BUILD.md5 in that directory)."; echo
} > $OUT
for arm in $ARMS; do
  $SAMTOOLS flagstat $W/prod.$arm.bam > $R/prod.$arm.flagstat; ps=$(sig $W/prod.$arm.bam); pf=$(sigfull $W/prod.$arm.bam)
  { echo "### $arm arm"; echo; echo "| item | production | test run 1 | identical | test run 2 | identical |"; echo "|---|---|---|---|---|---|"; } >> $OUT
  for k in 1 2; do $SAMTOOLS flagstat $R/$arm.$k.bam > $R/$arm.$k.flagstat; done
  s1=$(sig $R/$arm.1.bam); s2=$(sig $R/$arm.2.bam); f1=$(sigfull $R/$arm.1.bam); f2=$(sigfull $R/$arm.2.bam)
  u(){ grep 'Uniquely mapped reads %' $1 | cut -d'|' -f2 | xargs; }
  {
  echo "| uniquely mapped % | $(u $D/bam/$SID.$arm.Log.final.out) | $(u $R/$arm.1.Log.final.out) | $(chk "$(u $D/bam/$SID.$arm.Log.final.out)" "$(u $R/$arm.1.Log.final.out)") | $(u $R/$arm.2.Log.final.out) | $(chk "$(u $D/bam/$SID.$arm.Log.final.out)" "$(u $R/$arm.2.Log.final.out)") |"
  echo "| md5 records sorted by (name, flag, chr, pos, CIGAR, vW) | $ps | $s1 | $(chk $ps $s1) | $s2 | $(chk $ps $s2) |"
  echo "| md5 whole records (all tags), sorted | $pf | $f1 | $(chk $pf $f1) | $f2 | $(chk $pf $f2) |"
  echo "| flagstat | $(md5sum $R/prod.$arm.flagstat | cut -c1-8) | $(md5sum $R/$arm.1.flagstat | cut -c1-8) | $(chk "$(cat $R/prod.$arm.flagstat)" "$(cat $R/$arm.1.flagstat)") | $(md5sum $R/$arm.2.flagstat | cut -c1-8) | $(chk "$(cat $R/prod.$arm.flagstat)" "$(cat $R/$arm.2.flagstat)") |"
  } >> $OUT
  for k in 1 2; do
    if [ $arm = naive ]; then $SAMTOOLS view -@ 2 -b -e '![vW] || [vW]==1' $R/naive.$k.bam > $R/wasp.$k.bam; fi
  done
  echo >> $OUT
done
{ echo "### featureCounts count matrices (data rows: gene_id, count)"; echo; echo "| matrix | production | test run 1 | identical | test run 2 | identical |"; echo "|---|---|---|---|---|---|"; } >> $OUT
for job in "naive unique" "wasp unique" "fvb unique" "naive multi" "fvb multi"; do
  set -- $job; arm=$1; mode=$2; M=""; [ $mode = multi ] && M="-M --fraction"
  case " $ARMS " in *" naive "*) ;; *) [ $arm = naive ] || [ $arm = wasp ] && continue;; esac
  case " $ARMS " in *" fvb "*) ;; *) [ $arm = fvb ] && continue;; esac
  for k in 1 2; do $FC -a $GTF -o $R/$arm.$k.$mode.txt $M -s 0 -T 4 $PF $R/$arm.$k.bam > $R/$arm.$k.fc_$mode.log 2>&1; done
  p=$(fcmd5 $D/counts/$SID.$arm.$mode.txt); a=$(fcmd5 $R/$arm.1.$mode.txt); b=$(fcmd5 $R/$arm.2.$mode.txt)
  echo "| $arm $mode | $p | $a | $(chk $p $a) | $b | $(chk $p $b) |" >> $OUT
done
{
echo; echo "### Timings (seconds)"; echo; echo '```'; cat $R/timings.txt; echo '```'
echo; echo "Production STAR times for this animal (8 threads, sequential, built-in sort): naive $(awk '/STAR naive$/{a=$2} /STAR naive ok/{b=$2} END{gsub(/\]/,"",a); gsub(/\]/,"",b); print a" -> "b}' $D/logs/run_sample.log), fvb $(awk '/STAR fvb$/{a=$2} /STAR fvb ok/{b=$2} END{gsub(/\]/,"",a); gsub(/\]/,"",b); print a" -> "b}' $D/logs/run_sample.log)."
echo; echo "### Verdict"; echo
NBAD=$(grep -o "\*\*NO\*\*" $OUT | wc -l)
if [ $NBAD -eq 0 ]; then echo "**ADOPT**: every comparison identical (0 differences)."; else echo "**REJECT**: $NBAD comparison(s) differ; production continues unchanged (condition 2)."; fi
} >> $OUT
NBAD=$(grep -o "\*\*NO\*\*" $OUT | wc -l); log "test complete: $([ $NBAD -eq 0 ] && echo ADOPT || echo REJECT) ($NBAD differences)"
