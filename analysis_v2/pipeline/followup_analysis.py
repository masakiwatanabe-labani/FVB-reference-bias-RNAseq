#!/usr/bin/env python3
"""Follow-up analyses approved 2026-10-20 (user reply to the Phase C report). None of them changes the primary catalog or any
file written by bias_analysis.py; everything goes to NEW files under analysis_v2/results (RESULTS.md5 is regenerated by
followup_run.sh). Inputs are the final-run outputs only (rule 0.4-7: nothing is read from legacy/).

  1. negative_control/pyvt_fullsite_chr3_10_16.per_animal.tsv / .per_site.tsv
     Full 203,510-site identity count restricted to chr 3/10/16 (pyvt_fullsite_recount.sh) for the 13 PyVT animals and, as
     comparators with the same sites and command, the 8 C57BL/6J skin (single-end, like PyVT) and 8 C57BL/6J hypothalamus
     (paired-end) animals. Per animal x chromosome: n sites (depth >= 20), mean FVB-allele fraction, fraction of sites with
     AF > 0.9 / 0.1-0.9 / < 0.1, and the run of consecutive sites with AF >= 0.1 (a congenic segment shows up as a contiguous
     block, an artefact as isolated sites that the B6 comparators share).
  2. negative_control/catalog_swap_by_chrom_stratum.tsv
     Per-sample reference-swap ratio (log2 FVB-arm/naive-arm count, from *_reference_swap_per_gene.tsv) at catalog genes,
     stratified into genes on chr 10 or 16 versus all other chromosomes; PyVT, C57BL/6J and FVB/NJ animals of every tissue.
  3. negative_control/reference_swap_by_group.tsv
     The reference_swap_summary.tsv rows summarised per comparator group: PyVT (single-end), C57BL/6J skin (single-end),
     C57BL/6J paired-end tissues, FVB/NJ skin (single-end), FVB/NJ paired-end tissues (mean +/- sd over animals).
  4. sensitivity_matched/  (optional analysis 4, approved; Supplementary only, main catalog unchanged)
     "Matched-reference" strain contrast: C57BL/6J animals counted on the B6 reference (naive arm, unique) and FVB/NJ animals
     counted on the FVB/NJ reference (FVB arm, unique) in ONE edgeR model with the primary design of the tissue;
     bias_matched = logFC_matched - logFC_naive. catalog.matched.tsv applies the fixed criterion (>= 0.5 log2 in >= 2 tissues,
     in FVB GTF) to bias_matched; summary.tsv gives the overlap with the primary catalog and the threshold grid.
  5. negative_control/heldout_catalog_swap.tsv / .by_group.tsv
     Leave-one-tissue-out comparator for the PyVT negative control (see heldout()).
"""
import os, sys, subprocess, glob
import numpy as np, pandas as pd
PROJ="/usr/local/jupyter/FVB_bias"; RES=f"{PROJ}/analysis_v2/results"; CNT=f"{RES}/counts"; NC=f"{RES}/negative_control"; SM=f"{RES}/sensitivity_matched"
R=f"{PROJ}/analysis_v2/pipeline/run_edger.R"; MAN=f"{PROJ}/revision_v2/manifest/manifest.tsv"
BIAS_THR=0.5; MIN_TISSUES=2
os.makedirs(SM, exist_ok=True)
meta=pd.read_csv(f"{RES}/gene_meta.tsv", sep="\t", index_col=0)
cat=pd.read_csv(f"{RES}/catalog/catalog.primary.tsv", sep="\t", index_col=0)
man=pd.read_csv(MAN, sep="\t", dtype=str).set_index("sample_id")
PYVT="B6.FVB-Tg(MMTV-PyVT)634Mul/LellJ"
def group_of(sid):
    s=man.loc[sid,"strain"]; lay=man.loc[sid,"library_layout"]; t=man.loc[sid,"tissue"]
    if s==PYVT: return "PyVT (SE)"
    short={"C57BL/6J":"C57BL/6J","FVB/NJ":"FVB/NJ"}[s]
    return f"{short} {'skin (SE)' if lay=='SINGLE' else 'paired-end tissues'}"

# ---- 1. full-site chr 3/10/16 identity count ---------------------------------------------------------------------------
def fullsite():
    files=sorted(glob.glob(f"{PROJ}/analysis_v2/data/*/*/qc/*.ase.full_chr3_10_16.tsv"))
    if not files: print("[1] no full-site recount files yet"); return
    rows=[]; sites=[]
    for p in files:
        sid=os.path.basename(p).split(".ase.")[0]; a=pd.read_csv(p, sep="\t"); a=a[(a.refCount+a.altCount)>=20].copy()
        a["af"]=a.altCount/(a.refCount+a.altCount); a["sample_id"]=sid; a["group"]=group_of(sid); sites.append(a[["sample_id","group","contig","position","refCount","altCount","af"]])
        for c,g in a.sort_values("position").groupby("contig"):
            flag=(g.af>=0.1).values; best=run=0
            for f in flag: run=run+1 if f else 0; best=max(best,run)
            rows.append({"sample_id":sid,"group":group_of(sid),"chrom":c,"n_sites":len(g),"mean_af":g.af.mean(),"frac_af_gt_0.9":(g.af>0.9).mean(),
                         "frac_af_0.1_0.9":((g.af>=0.1)&(g.af<=0.9)).mean(),"frac_af_lt_0.1":(g.af<0.1).mean(),"n_sites_af_ge_0.1":int(flag.sum()),
                         "longest_run_af_ge_0.1":best,"min_pos_af_ge_0.1":int(g.position[g.af>=0.1].min()) if flag.any() else np.nan,"max_pos_af_ge_0.1":int(g.position[g.af>=0.1].max()) if flag.any() else np.nan})
    per=pd.DataFrame(rows).sort_values(["group","sample_id","chrom"]); per.to_csv(f"{NC}/pyvt_fullsite_chr3_10_16.per_animal.tsv", sep="\t", index=False)
    st=pd.concat(sites, ignore_index=True)
    # site-level: a site is "shared" when it has AF >= 0.1 in at least one B6 comparator too (then it is a site property, not a PyVT property)
    b6=st[st.group.str.startswith("C57BL/6J")]; b6hit=set(zip(b6.contig[b6.af>=0.1],b6.position[b6.af>=0.1])); b6cov=b6.groupby(["contig","position"]).size()
    py=st[st.group=="PyVT (SE)"]; hit=py[py.af>=0.1].copy(); hit["also_af_ge_0.1_in_B6_comparator"]=[(c,p) in b6hit for c,p in zip(hit.contig,hit.position)]
    hit["n_B6_comparators_covered"]=[int(b6cov.get((c,p),0)) for c,p in zip(hit.contig,hit.position)]
    hit.sort_values(["contig","position","sample_id"]).to_csv(f"{NC}/pyvt_fullsite_chr3_10_16.per_site.tsv", sep="\t", index=False)
    g=per.groupby(["group","chrom"]).agg(n_animals=("sample_id","nunique"),mean_n_sites=("n_sites","mean"),mean_af=("mean_af","mean"),max_af=("mean_af","max"),
                                          mean_frac_af_mid=("frac_af_0.1_0.9","mean"),mean_frac_af_hi=("frac_af_gt_0.9","mean"),max_longest_run=("longest_run_af_ge_0.1","max")).reset_index()
    g.to_csv(f"{NC}/pyvt_fullsite_chr3_10_16.by_group.tsv", sep="\t", index=False)
    print("[1] per-group summary"); print(g.round(3).to_string(index=False))
    print(f"[1] PyVT sites with AF >= 0.1: {len(hit)} (distinct sites {hit[['contig','position']].drop_duplicates().shape[0]}); of which also AF >= 0.1 in a B6 comparator: {int(hit['also_af_ge_0.1_in_B6_comparator'].sum())}")

# ---- 2. catalog swap ratio stratified by chromosome ----------------------------------------------------------------------
def swap_strata():
    chrom=meta["chrom"].reindex(cat.index); s1=list(cat.index[chrom.isin(["10","16"])]); s2=list(cat.index[~chrom.isin(["10","16"])])
    rows=[]
    for p in sorted(glob.glob(f"{NC}/*_reference_swap_per_gene.tsv")):
        r=pd.read_csv(p, sep="\t", index_col=0); label=os.path.basename(p).split("_reference_swap")[0]
        for s in r.columns:
            a=r.reindex(s1)[s].dropna(); b=r.reindex(s2)[s].dropna(); o=r[s].dropna()
            rows.append({"sample_id":s,"tissue_label":label,"group":group_of(s),"n_catalog_chr10_16":len(a),"median_swap_catalog_chr10_16":a.median(),
                         "n_catalog_other":len(b),"median_swap_catalog_other":b.median(),"median_swap_all_genes":o.median(),"frac_ge_0.5_catalog_chr10_16":(a>=0.5).mean(),"frac_ge_0.5_catalog_other":(b>=0.5).mean()})
    d=pd.DataFrame(rows).sort_values(["group","sample_id"]); d.to_csv(f"{NC}/catalog_swap_by_chrom_stratum.tsv", sep="\t", index=False)
    g=d.groupby("group").agg(n_animals=("sample_id","count"),chr10_16_median=("median_swap_catalog_chr10_16","mean"),chr10_16_sd=("median_swap_catalog_chr10_16","std"),
                             other_median=("median_swap_catalog_other","mean"),other_sd=("median_swap_catalog_other","std")).reset_index()
    print(f"[2] catalog genes on chr 10/16: {len(s1)}, other: {len(s2)}"); print(g.round(3).to_string(index=False))

# ---- 3. comparator groups --------------------------------------------------------------------------------------------------
def swap_groups():
    d=pd.read_csv(f"{NC}/reference_swap_summary.tsv", sep="\t"); d["group"]=d.sample_id.map(group_of)
    cols=["median","mean","q05","q95","frac_ge_0.5","frac_le_-0.5","catalog_genes_median_swap"]
    g=d.groupby("group").agg(n_animals=("sample_id","count"),tissues=("tissue",lambda x:",".join(sorted(set(x)))),**{f"{c}_mean":(c,"mean") for c in cols},**{f"{c}_sd":(c,"std") for c in cols},
                             catalog_median_swap_min=("catalog_genes_median_swap","min"),catalog_median_swap_max=("catalog_genes_median_swap","max")).reset_index()
    g.to_csv(f"{NC}/reference_swap_by_group.tsv", sep="\t", index=False)
    print("[3] reference swap by group"); print(g[["group","n_animals","median_mean","frac_ge_0.5_mean","catalog_genes_median_swap_mean","catalog_genes_median_swap_sd","catalog_median_swap_min","catalog_median_swap_max"]].round(3).to_string(index=False))

# ---- 4. matched-reference sensitivity ------------------------------------------------------------------------------------
CONTROL_LEVELS=("water","control")
def design_for(ss):
    sexterm=" sex +" if ss["sex"].fillna("").nunique()>1 else ""
    return (f"~ diet +{sexterm} strain" if ss["diet"].nunique()>1 else f"~{sexterm} strain"),"strainFVB"
def matched():
    os.makedirs(f"{SM}/counts", exist_ok=True); os.makedirs(f"{SM}/edger", exist_ok=True); os.makedirs(f"{SM}/bias", exist_ok=True)
    tabs={}
    for t in ("adipose","hypothalamus","liver","skin"):
        ss=pd.read_csv(f"{CNT}/{t}.samples.tsv", sep="\t"); nv=pd.read_csv(f"{CNT}/{t}.naive.unique.tsv", sep="\t", index_col=0); fv=pd.read_csv(f"{CNT}/{t}.fvb.unique.tsv", sep="\t", index_col=0)
        b6=ss.sample_id[ss.strain=="C57BL/6J"].tolist(); fvb=ss.sample_id[ss.strain=="FVB/NJ"].tolist()
        g=nv.index.intersection(fv.index); m=pd.concat([nv.loc[g,b6],fv.loc[g,fvb]],axis=1)[ss.sample_id.tolist()]; m.index.name="gene_id"
        cp=f"{SM}/counts/{t}.matched.unique.tsv"; m.to_csv(cp, sep="\t")
        formula,coef=design_for(ss); out=f"{SM}/edger/{t}.primary.matched.unique.tsv"
        if not os.path.exists(out):
            r=subprocess.run(["Rscript",R,cp,f"{CNT}/{t}.samples.tsv",formula,coef,out,""],capture_output=True,text=True)
            if r.returncode!=0: sys.exit(f"edgeR failed {t} matched: {r.stderr[-2000:]}")
            print("[4]",r.stdout.strip())
        mt=pd.read_csv(out, sep="\t", index_col=0); nvr=pd.read_csv(f"{RES}/edger/{t}.primary.naive.unique.tsv", sep="\t", index_col=0); pb=pd.read_csv(f"{RES}/bias/{t}.primary.tsv", sep="\t", index_col=0)
        gg=mt.index.intersection(nvr.index)
        b=pd.DataFrame({"tissue":t,"logFC_naive":nvr.loc[gg,"logFC"],"logFC_matched":mt.loc[gg,"logFC"],"FDR_matched":mt.loc[gg,"FDR"]}); b["bias_matched"]=b.logFC_matched-b.logFC_naive
        b["bias_primary"]=pb["bias"].reindex(gg); b.index.name="gene_id"; b.to_csv(f"{SM}/bias/{t}.matched.tsv", sep="\t"); tabs[t]=b
    long=pd.concat([v.assign(gene_id=v.index) for v in tabs.values()], ignore_index=True); long.to_csv(f"{SM}/bias/all_tissues.matched.tsv", sep="\t", index=False)
    wide=long.pivot(index="gene_id",columns="tissue",values="bias_matched"); tissues=list(wide.columns); in_fvb=meta["in_fvb_gtf"].reindex(wide.index).eq("Y")
    hit=wide>=BIAS_THR; n_hit=hit.sum(axis=1); cm=wide[(n_hit>=MIN_TISSUES)&in_fvb].copy()
    cm["n_tissues"]=n_hit[cm.index]; cm["mean_bias_matched"]=wide.loc[cm.index].mean(axis=1); cm["gene_name"]=meta.gene_name.reindex(cm.index); cm["biotype"]=meta.biotype.reindex(cm.index)
    cm["in_primary_catalog"]=np.where(cm.index.isin(cat.index),"Y","N"); cm["mean_bias_primary"]=cat["mean_bias"].reindex(cm.index)
    cm=cm.sort_values("mean_bias_matched",ascending=False); cm.index.name="gene_id"
    cm[["gene_name","biotype","n_tissues","mean_bias_matched"]+tissues+["in_primary_catalog","mean_bias_primary"]].to_csv(f"{SM}/catalog.matched.tsv", sep="\t")
    both=cm.index.intersection(cat.index); rows=[{"item":"genes tested (matched)","value":len(wide)},{"item":"primary catalog","value":len(cat)},{"item":"matched catalog","value":len(cm)},
          {"item":"in both","value":len(both)},{"item":"primary only","value":len(cat.index.difference(cm.index))},{"item":"matched only","value":len(cm.index.difference(cat.index))}]
    for t in tissues:
        both_t=long[long.tissue==t]; rows.append({"item":f"Spearman rho bias_primary vs bias_matched ({t})","value":round(float(both_t[["bias_primary","bias_matched"]].dropna().corr(method="spearman").iloc[0,1]),4)})
        rows.append({"item":f"median bias_matched ({t})","value":round(float(both_t.bias_matched.median()),4)})
    pw=pd.read_csv(f"{RES}/bias/all_tissues.primary.tsv", sep="\t").pivot(index="gene_id",columns="tissue",values="bias")
    for thr in (0.25,0.5,1.0):
        for k in range(1,len(tissues)+1):
            a=set(wide.index[((wide>=thr).sum(axis=1)>=k)&in_fvb]); p=set(pw.index[((pw>=thr).sum(axis=1)>=k)&meta["in_fvb_gtf"].reindex(pw.index).eq("Y")])
            rows.append({"item":f"grid thr={thr} min_tissues={k}: primary / matched / both","value":f"{len(p)} / {len(a)} / {len(a&p)}"})
    pd.DataFrame(rows).to_csv(f"{SM}/summary.tsv", sep="\t", index=False); print("[4] matched-reference summary"); print(pd.DataFrame(rows).to_string(index=False))
    # primary-catalog genes that do NOT survive the matched definition, with their matched values (for the Supplementary note)
    miss=cat.loc[cat.index.difference(cm.index),["gene_name","biotype","n_tissues","mean_bias"]].join(wide.loc[:,tissues].add_prefix("matched_")); miss.to_csv(f"{SM}/primary_catalog_not_in_matched.tsv", sep="\t")

# ---- 5. held-out comparison for the negative control ------------------------------------------------------------------
def heldout():
    """The C57BL/6J animals of the four strain-comparison tissues took part in selecting the catalog (bias = logFC_FVBref - logFC_naive
    is large when FVB/NJ reads gain on the FVB reference AND/OR C57BL/6J reads lose on it), so their catalog-gene swap ratio is
    inflated by the selection itself, whereas the PyVT animals never entered the selection. Fair comparator: leave one tissue out,
    select the catalog from the other three (same fixed criterion: >= 0.5 in >= 2 tissues, in FVB GTF), and compare the swap ratio
    at those genes in the held-out tissue's C57BL/6J and FVB/NJ animals with the PyVT animals at the same genes.
    Output: negative_control/heldout_catalog_swap.tsv (one row per animal x held-out catalog) and .by_group.tsv."""
    wide=pd.read_csv(f"{RES}/bias/all_tissues.primary.tsv", sep="\t").pivot(index="gene_id",columns="tissue",values="bias"); in_fvb=meta["in_fvb_gtf"].reindex(wide.index).eq("Y")
    swap={t:pd.read_csv(f"{NC}/{t}_reference_swap_per_gene.tsv", sep="\t", index_col=0) for t in list(wide.columns)+["pyvt"]}
    rl=pd.read_csv(f"{RES}/qc/mapping_stats_per_sample.tsv", sep="\t").set_index("sample_id") if os.path.exists(f"{RES}/qc/mapping_stats_per_sample.tsv") else None
    rows=[]
    for held in wide.columns:
        others=[c for c in wide.columns if c!=held]; sel=wide.index[((wide[others]>=BIAS_THR).sum(axis=1)>=MIN_TISSUES)&in_fvb]
        for label in (held,"pyvt"):
            r=swap[label].reindex(sel).dropna(how="all")
            for s in r.columns:
                v=r[s].dropna(); rows.append({"held_out_tissue":held,"n_catalog_genes_from_other_tissues":len(sel),"sample_id":s,"group":group_of(s),"evaluated_in":label,
                                               "n_genes_evaluated":len(v),"median_swap":v.median(),"mean_swap":v.mean(),"frac_ge_0.5":(v>=0.5).mean(),"frac_le_-0.5":(v<=-0.5).mean(),
                                               "read_length":man.loc[s,"read_length"],"library_layout":man.loc[s,"library_layout"]})
    d=pd.DataFrame(rows); d.to_csv(f"{NC}/heldout_catalog_swap.tsv", sep="\t", index=False)
    g=d.groupby(["held_out_tissue","group"]).agg(n_catalog=("n_catalog_genes_from_other_tissues","first"),n_animals=("sample_id","count"),median_swap_mean=("median_swap","mean"),median_swap_sd=("median_swap","std"),
                                                 frac_le_m0p5_mean=("frac_le_-0.5","mean"),read_length=("read_length",lambda x:",".join(sorted(set(map(str,x)))))).reset_index()
    g.to_csv(f"{NC}/heldout_catalog_swap.by_group.tsv", sep="\t", index=False); print("[5] held-out catalog swap by group"); print(g.round(3).to_string(index=False))

if __name__=="__main__":
    which=sys.argv[1:] or ["1","2","3","4","5"]
    if "5" in which: heldout()
    if "1" in which: fullsite()
    if "2" in which: swap_strata()
    if "3" in which: swap_groups()
    if "4" in which: matched()
    print("followup_analysis DONE")
